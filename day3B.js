function checkResult(marks) {
 if (marks>=90) {
    console.log("Excellent");
 }
if (marks>=75) {
    console.log("Very Good");
 }
if (marks>=50) {
    console.log("Good");
 }
if (marks>=33) {
    console.log("Pass");
 }
 else{
    console.log("Fail");
    
 }
}
